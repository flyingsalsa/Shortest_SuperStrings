"""Summarise the OpenAI (2026) 2-approximation against greedy and OPT.

    python scripts/two_approx_summary.py [--out results/two_approx]

Three data sources (all deterministic, no timing used in conclusions):

1. ``results/two_approx/results.jsonl`` - the run of ``configs/two_approx.json``
   (greedy, exact DP and two_approx rows from the runner).
2. ``results/standard/{instances,results}.jsonl.gz`` - the committed standard
   experiment.  two_approx is run here on every instance with an exact OPT
   and compared with the STORED OPT and greedy lengths (no DP is re-run).
3. Shibata's S_{k,t} (``scs/shibata.py``), OPT certified by the counting bound
   n + k - 1 (see FINDINGS section 3b), compared with the paper's scripted
   greedy length t(9s+1)+1.

Writes ``summary.md`` and ``standard_rescore.jsonl`` to ``--out``.
"""
from __future__ import annotations

import argparse
import gzip
import json
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scs.preprocess import preprocess          # noqa: E402
from scs.shibata import build_instance         # noqa: E402
from scs.two_approx import two_approx          # noqa: E402
from scs.validate import check_superstring     # noqa: E402

SHIBATA_GRID = [(10, 1), (10, 2), (10, 4), (10, 9), (12, 1), (12, 8), (16, 1), (20, 1)]


def read_jsonl(path: Path):
    op = gzip.open if path.suffix == ".gz" else open
    with op(path, "rt", encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def per_instance(rows):
    """iid -> dict(opt, greedy lengths, two_approx row, family, n)."""
    out = defaultdict(lambda: {"greedy": {}, "two": None, "opt": None})
    for r in rows:
        if r["status"] != "ok":
            continue
        d = out[r["instance_id"]]
        d["family"], d["n"] = r["family"], r["n"]
        if r["algorithm"] == "exact_dp":
            d["opt"] = r["length"]
        elif r["algorithm"] == "greedy":
            d["greedy"][(r["policy"], r["tie_run"])] = r["length"]
        elif r["algorithm"] == "two_approx":
            d["two"] = r
    return out


def stats(xs):
    xs = sorted(xs)
    return (f"{statistics.mean(xs):.3f}", f"{xs[len(xs) // 2]:.3f}", f"{xs[-1]:.3f}") if xs else ("-",) * 3


def table(records, key):
    """records: list of dict(family, ratio_two, ratio_lowest, ratio_worst, ratio_best, w_ratio, cmp)."""
    groups = defaultdict(list)
    for r in records:
        groups[key(r)].append(r)
    lines = ["| group | instances | two_approx/OPT mean / median / max | W/OPT mean | "
             "greedy lowest_id/OPT mean | greedy worst-run/OPT mean / max | "
             "two_approx < best greedy | = | > worst greedy |",
             "|---|---|---|---|---|---|---|---|---|"]
    for g in sorted(groups, key=str) + ["**all**"]:
        rs = records if g == "**all**" else groups[g]
        two = stats([r["two"] for r in rs])
        w = statistics.mean(r["w"] for r in rs)
        low = statistics.mean(r["low"] for r in rs)
        worst = stats([r["worst"] for r in rs])
        beat = sum(r["two"] < r["best"] for r in rs)
        tie = sum(r["two"] == r["best"] for r in rs)
        above = sum(r["two"] > r["worst"] for r in rs)
        lines.append(f"| {g} | {len(rs)} | {' / '.join(two)} | {w:.3f} | {low:.3f} | "
                     f"{worst[0]} / {worst[2]} | {beat} | {tie} | {above} |")
    return lines


def record(fam, n, opt, two_len, W, greedy_lengths):
    gl = list(greedy_lengths.values())
    return {"family": fam, "n": n, "two": two_len / opt, "w": W / opt,
            "low": greedy_lengths[("lowest_id", None)] / opt,
            "best": min(gl) / opt, "worst": max(gl) / opt}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results/two_approx")
    a = ap.parse_args()
    out = ROOT / a.out
    md = ["# OpenAI (2026) 2-approximation vs greedy and OPT", "",
          "Generated by `scripts/two_approx_summary.py`. Ratios are lengths divided by exact OPT; "
          "'worst-run' is the longest of the 13 greedy runs (3 deterministic policies + "
          "random ties) of an instance, 'best greedy' the shortest. Counts in the last three "
          "columns compare two_approx with best/worst greedy on the same instance.", ""]

    # 1. dedicated run
    run = per_instance(read_jsonl(out / "results.jsonl"))
    recs, ops, viol = [], Counter(), 0
    for iid, d in run.items():
        if d["opt"] is None or d["two"] is None:
            continue
        t = d["two"]
        viol += (t["length"] > 2 * d["opt"]) or (t["lower_bound_W"] > d["opt"])
        recs.append(record(d["family"], d["n"], d["opt"], t["length"], t["lower_bound_W"], d["greedy"]))
        for k in t["two_approx_ops"]:
            ops[k] += 1
    md += ["## 1. `configs/two_approx.json`", "",
           f"{len(recs)} instances with exact OPT; violations of `W <= OPT` or `length <= 2 OPT`: {viol}.", ""]
    md += table(recs, lambda r: r["family"])
    md += ["", "Connection operations used (instances using each kind): "
           + ", ".join(f"`{k}` {v}" for k, v in sorted(ops.items())), ""]

    # 2. standard experiment re-score
    insts = {i["instance_id"]: i for i in read_jsonl(ROOT / "results/standard/instances.jsonl.gz")}
    std = per_instance(read_jsonl(ROOT / "results/standard/results.jsonl.gz"))
    recs2, rescore, viol2, errors = [], [], 0, 0
    for iid in sorted(std):
        d = std[iid]
        if d["opt"] is None or ("lowest_id", None) not in d["greedy"]:
            continue
        raw = insts[iid]["strings"]
        R = preprocess(raw).retained
        try:
            res = two_approx(R)
        except Exception as e:  # noqa: BLE001  report, never hide
            errors += 1
            rescore.append({"instance_id": iid, "error": f"{type(e).__name__}: {e}"})
            continue
        assert check_superstring(raw, res.superstring) == []
        viol2 += (res.length > 2 * d["opt"]) or (res.W > d["opt"])
        recs2.append(record(d["family"], d["n"], d["opt"], res.length, res.W, d["greedy"]))
        rescore.append({"instance_id": iid, "family": d["family"], "n": d["n"], "opt": d["opt"],
                        "two_approx": res.length, "W": res.W, "added_cost": res.added_cost,
                        "greedy_lowest_id": d["greedy"][("lowest_id", None)],
                        "greedy_best": min(d["greedy"].values()),
                        "greedy_worst": max(d["greedy"].values())})
    with open(out / "standard_rescore.jsonl", "w", encoding="utf-8") as f:
        for r in rescore:
            f.write(json.dumps(r) + "\n")
    md += ["## 2. Committed standard experiment, re-scored", "",
           f"{len(recs2)} instances of `results/standard` with exact OPT (stored OPT and greedy "
           f"lengths re-used; two_approx run fresh). Errors: {errors}. Violations of "
           f"`W <= OPT` or `length <= 2 OPT`: {viol2}.", ""]
    md += table(recs2, lambda r: r["family"])
    md += ["", "By retained n (all families):", ""]
    md += table(recs2, lambda r: f"n={r['n']:02d}")
    md += [""]

    # 3. Shibata
    md += ["## 3. Shibata's S_{k,t} (greedy can exceed 2 OPT here)", "",
           "| k | t | n | OPT (certified) | W | two_approx | two_approx/OPT | scripted greedy | greedy/OPT |",
           "|---|---|---|---|---|---|---|---|---|"]
    for k, t in SHIBATA_GRID:
        inst = build_instance(k, t)
        s = k // 2
        R = preprocess(inst["strings"]).retained
        opt, g = t * (4 * s + 2) + k - 1, t * (9 * s + 1) + 1
        res = two_approx(R)
        assert check_superstring(inst["strings"], res.superstring) == []
        md.append(f"| {k} | {t} | {len(R)} | {opt} | {res.W} | {res.length} | "
                  f"{res.length / opt:.3f} | {g} | {g / opt:.3f} |")
    md.append("")
    (out / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
